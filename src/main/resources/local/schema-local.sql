-- In-memory H2 schema of a locally hosted server (local profile only, never the shared database).
--
-- ../database/migration stays the source of truth for the shared PostgreSQL database; this file
-- only mirrors the tables and columns the game server reads during Practice and PVE matches, as
-- of database V035 (baseline V001 plus V003, V010, V012, V018, V026, V034, V035). When a migration
-- adds a column the game reads, add it here too: the static data importer drops columns this file
-- does not declare, with a warning.
--
-- Deliberately loose: no foreign keys, no check constraints and unbounded varchar, so the static
-- data the lobby exports always loads in any table order. Postgres enums are plain varchar and
-- jsonb is CLOB; the game reads neither as structured data.
--
-- Tables filled from static.json: everything except user_magics and user_scenarios. users,
-- decks and deck_cards receive the bot rows from static.json and the player's row, deck and
-- owned magics from POST /api/local/sessions. Columns the game inserts into without an id are
-- identities, restarted past the imported rows after the import.

CREATE TABLE users (
    id BIGINT PRIMARY KEY,
    selected_deck_id BIGINT,
    mmr SMALLINT DEFAULT 1000 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR DEFAULT 'Online' NOT NULL,
    total_wins INTEGER DEFAULT 0 NOT NULL,
    novice_progress REAL DEFAULT 0.5 NOT NULL,
    appearance VARCHAR DEFAULT 'default' NOT NULL
);

CREATE TABLE decks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR,
    user_id BIGINT NOT NULL
);

CREATE TABLE deck_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_id BIGINT NOT NULL,
    magic_id BIGINT NOT NULL,
    count INTEGER DEFAULT 1 NOT NULL
);

CREATE TABLE user_magics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    magic_id BIGINT,
    count INTEGER DEFAULT 3 NOT NULL
);

CREATE TABLE user_scenarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    scenario_id BIGINT,
    state VARCHAR DEFAULT 'INACTIVE' NOT NULL
);

CREATE TABLE magics (
    id BIGINT PRIMARY KEY,
    name VARCHAR NOT NULL,
    access_type VARCHAR DEFAULT 'DEFAULT' NOT NULL,
    element VARCHAR DEFAULT 'None' NOT NULL,
    updated_at TIMESTAMP,
    unlock_condition_type VARCHAR,
    unlock_required_value INTEGER,
    cast_kind VARCHAR,
    prefab VARCHAR,
    indicator CLOB,
    purpose VARCHAR DEFAULT 'PLAYER' NOT NULL
);

CREATE TABLE game_objects (
    id BIGINT PRIMARY KEY,
    name VARCHAR
);

CREATE TABLE parameters (
    id BIGINT PRIMARY KEY,
    name VARCHAR
);

CREATE TABLE parameter_values (
    id BIGINT PRIMARY KEY,
    parameter_id BIGINT,
    game_object_id BIGINT,
    value DOUBLE PRECISION,
    updated_at TIMESTAMP
);

CREATE TABLE magic_parameters (
    id BIGINT PRIMARY KEY,
    magic_id BIGINT NOT NULL,
    parameter_id BIGINT NOT NULL,
    value DOUBLE PRECISION,
    updated_at TIMESTAMP
);

CREATE TABLE prefab_elements (
    prefab VARCHAR NOT NULL,
    element VARCHAR NOT NULL
);

CREATE TABLE magic_game_object_aliases (
    magic_name VARCHAR NOT NULL,
    game_object_name VARCHAR NOT NULL,
    reason CLOB
);

CREATE TABLE tags (
    id BIGINT PRIMARY KEY,
    name VARCHAR
);

CREATE TABLE tag_counter_rules (
    id BIGINT PRIMARY KEY,
    attacker_tag_id BIGINT NOT NULL,
    target_tag_id BIGINT NOT NULL,
    weight DOUBLE PRECISION DEFAULT 1.0 NOT NULL
);

CREATE TABLE game_object_tags (
    id BIGINT,
    game_object_id BIGINT,
    tag_id BIGINT
);

CREATE TABLE magic_tags (
    magic_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL
);

CREATE TABLE bot_personas (
    user_id BIGINT PRIMARY KEY,
    name VARCHAR NOT NULL,
    tier VARCHAR DEFAULT 'BEGINNER' NOT NULL,
    thinking_time_ms INTEGER DEFAULT 250 NOT NULL,
    reaction_interval_frames INTEGER DEFAULT 8 NOT NULL,
    counter_aggression DOUBLE PRECISION DEFAULT 0.25 NOT NULL,
    enabled BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    hospitality BOOLEAN DEFAULT FALSE NOT NULL,
    temperament VARCHAR DEFAULT 'WARM' NOT NULL
);

CREATE TABLE adventures (
    id BIGINT PRIMARY KEY,
    name VARCHAR NOT NULL,
    access_type VARCHAR DEFAULT 'FREE' NOT NULL
);

CREATE TABLE stages (
    id BIGINT PRIMARY KEY,
    adventure_id BIGINT,
    map_type VARCHAR DEFAULT 'GRASSLAND' NOT NULL
);

CREATE TABLE scenarios (
    id BIGINT PRIMARY KEY,
    stage_id BIGINT
);

CREATE TABLE pve_scenario_objectives (
    id BIGINT PRIMARY KEY,
    installer_id VARCHAR NOT NULL,
    sort_order INTEGER NOT NULL,
    scenario_id BIGINT DEFAULT 1 NOT NULL
);

CREATE TABLE pve_scenario_installers (
    id BIGINT PRIMARY KEY,
    installer_id VARCHAR NOT NULL,
    prefab_type VARCHAR NOT NULL,
    master VARCHAR NOT NULL,
    position_x INTEGER NOT NULL,
    position_y INTEGER NOT NULL,
    position_z INTEGER NOT NULL,
    sort_order INTEGER NOT NULL,
    scenario_id BIGINT DEFAULT 1 NOT NULL,
    max_hp INTEGER
);

CREATE TABLE pve_scenario_events (
    id BIGINT PRIMARY KEY,
    event_id VARCHAR NOT NULL,
    trigger_type VARCHAR NOT NULL,
    trigger_value INTEGER NOT NULL,
    speaker_installer_id VARCHAR,
    message_key VARCHAR,
    sort_order INTEGER NOT NULL,
    scenario_id BIGINT DEFAULT 1 NOT NULL,
    target_installer_id VARCHAR
);

CREATE TABLE pve_scenario_event_lines (
    id BIGINT PRIMARY KEY,
    event_row_id BIGINT NOT NULL,
    line_order INTEGER NOT NULL,
    line_text VARCHAR NOT NULL
);

CREATE TABLE pve_scenario_event_actions (
    id BIGINT PRIMARY KEY,
    event_row_id BIGINT NOT NULL,
    action_order INTEGER NOT NULL,
    action_type VARCHAR NOT NULL,
    installer_id VARCHAR,
    prefab_type VARCHAR,
    count INTEGER,
    interval_seconds REAL,
    position_x INTEGER,
    position_z INTEGER,
    max_hp INTEGER,
    bgm_key VARCHAR
);

CREATE TABLE pve_scenario_rules (
    scenario_id BIGINT PRIMARY KEY,
    win_condition VARCHAR DEFAULT 'DestroyObjectives' NOT NULL,
    survive_seconds INTEGER
);

CREATE TABLE pve_scenario_shields (
    scenario_id BIGINT NOT NULL,
    installer_id VARCHAR NOT NULL,
    source_installer_id VARCHAR NOT NULL,
    PRIMARY KEY (scenario_id, installer_id, source_installer_id)
);
